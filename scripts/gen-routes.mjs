/**
 * Derives Next.js route wrappers and tRPC wiring from the app manifests.
 *
 *   npm run gen:routes
 *
 * Add a module: create apps/<app>/<module>/{page.tsx,router.ts} and add one
 * entry to that app's app.config.ts. Everything else is generated here.
 */
import { createJiti } from "jiti";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const jiti = createJiti(root, { interopDefault: true });

const apps = [
	(await jiti("./src/apps/itsm/app.config.ts")).itsmApp,
	(await jiti("./src/apps/mes/app.config.ts")).mesApp,
];

const header = "// GENERATED by `npm run gen:routes` — do not edit by hand.\n";

function camelCase(value) {
	return value.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^([A-Z])/, (c) => c.toLowerCase());
}

function allModules(mods) {
	return mods.flatMap((mod) => [mod, ...allModules(mod.children ?? [])]);
}

async function writeIfChanged(path, content) {
	let current = null;
	try {
		current = await readFile(path, "utf8");
	} catch {
		// new file
	}
	if (current === content) return false;
	await mkdir(dirname(path), { recursive: true });
	await writeFile(path, content, "utf8");
	return true;
}

async function appFolderExists(appId) {
	try {
		await readdir(join(root, "src", "apps", appId));
		return true;
	} catch {
		return false;
	}
}

let wrappers = 0;
let missing = [];

for (const app of apps) {
	if (!(await appFolderExists(app.id))) {
		missing.push(`apps/${app.id} (folder does not exist)`);
		continue;
	}
	for (const mod of allModules(app.modules)) {
		if (mod.hasPage === false || mod.href !== undefined) continue;
		const segment = mod.segment ?? mod.id;
		const routeDir = join(root, "src", "app", ...app.urlPrefix.split("/").filter(Boolean), ...segment.split("/").filter(Boolean));
		const content = `${header}import { Page } from "@/apps/${app.id}/${mod.id}/page";

export default Page;
`;
		if (await writeIfChanged(join(routeDir, "page.tsx"), content)) wrappers++;

		try {
			await readdir(join(root, "src", "apps", app.id, mod.id));
		} catch {
			missing.push(`apps/${app.id}/${mod.id}/page.tsx`);
		}
	}
}

// tRPC wiring: ITSM stays flat at the root, MES stays under `mes` so existing
// `trpc.assets.*` / `trpc.mes.*` client paths do not change.
const imports = [];
const itsmEntries = [];
const mesEntries = [];
for (const app of apps) {
	for (const mod of allModules(app.modules)) {
		if (mod.hasRouter === false) continue;
		const name = `${camelCase(mod.id)}Router`;
		imports.push(`import { router as ${name} } from "./${app.id}/${mod.id}/router";`);
		const key = mod.routerKey ?? mod.id;
		const property = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
		(app.id === "itsm" ? itsmEntries : mesEntries).push(`\t${property}: ${name},`);
	}
}

const registry = `${header}import { router } from "@/server/trpc";

${imports.join("\n")}

/** Flat ITSM procedures — preserves existing trpc.<module>.* paths. */
export const itsmRouters = {
${itsmEntries.join("\n")}
};

/** MES procedures stay namespaced under trpc.mes.*. */
export const mesRouter = router({
${mesEntries.join("\n")}
});
`;
if (await writeIfChanged(join(root, "src", "apps", "server-registry.ts"), registry)) wrappers++;

console.log(`gen:routes — ${wrappers} file(s) written`);
if (missing.length) {
	console.warn(`gen:routes — ${missing.length} module folder(s) still need creating:`);
	for (const path of missing.slice(0, 20)) console.warn(`  - ${path}`);
	if (missing.length > 20) console.warn(`  ... and ${missing.length - 20} more`);
}
